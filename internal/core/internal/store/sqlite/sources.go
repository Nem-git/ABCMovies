package sqlite

import (
	"context"
	"crypto/rand"
	"database/sql"
	"encoding/hex"
	"fmt"
	"time"
)

func (s *Store) GetSourceByVerifiedIdentity(ctx context.Context, connectorID, verifiedExternalID string) (*Source, error) {
	src := &Source{}
	err := s.db.QueryRowContext(ctx,
		`SELECT source_id, connector_id, verified_external_id, endpoint, display_name, status, status_detail, created_by, created, updated
		   FROM sources WHERE connector_id = ? AND verified_external_id = ?`,
		connectorID, verifiedExternalID,
	).Scan(&src.SourceID, &src.ConnectorID, &src.VerifiedExternalID, &src.Endpoint, &src.DisplayName, &src.Status, &src.StatusDetail, &src.CreatedBy, &src.Created, &src.Updated)
	if err == sql.ErrNoRows {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("get source by verified identity: %w", err)
	}
	return src, nil
}

// CreateSource inserts a verified, connected source and returns it.
// The source_id is generated by the store. A uniqueness violation on
// (connector_id, verified_external_id) is returned as an error (core should
// dedup first via GetSourceByVerifiedIdentity; the UNIQUE constraint is the
// final guard).

func (s *Store) CreateSource(ctx context.Context, in Source) (*Source, error) {
	id := make([]byte, 16)
	if _, err := rand.Read(id); err != nil {
		return nil, fmt.Errorf("generate source id: %w", err)
	}
	now := time.Now().UTC()
	src := in
	src.SourceID = "src_" + hex.EncodeToString(id)
	src.Created = now
	src.Updated = now
	if _, err := s.db.ExecContext(ctx,
		`INSERT INTO sources (source_id, connector_id, verified_external_id, endpoint, display_name, status, status_detail, created_by, created, updated)
		 VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		src.SourceID, src.ConnectorID, src.VerifiedExternalID, src.Endpoint, src.DisplayName, src.Status, src.StatusDetail, src.CreatedBy, src.Created, src.Updated,
	); err != nil {
		if isUniqueConstraint(err) {
			return nil, ErrDuplicateVerifiedIdentity
		}
		return nil, fmt.Errorf("insert source: %w", err)
	}
	return &src, nil
}

// GetSource returns the source with the given source_id, or ErrNotFound.

func (s *Store) GetSource(ctx context.Context, sourceID string) (*Source, error) {
	src := &Source{}
	err := s.db.QueryRowContext(ctx,
		`SELECT source_id, connector_id, verified_external_id, endpoint, display_name, status, status_detail, created_by, created, updated
		   FROM sources WHERE source_id = ?`, sourceID,
	).Scan(&src.SourceID, &src.ConnectorID, &src.VerifiedExternalID, &src.Endpoint, &src.DisplayName, &src.Status, &src.StatusDetail, &src.CreatedBy, &src.Created, &src.Updated)
	if err == sql.ErrNoRows {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("get source: %w", err)
	}
	return src, nil
}

// ListSources returns all connected sources (non-sensitive summaries), newest first.
// Build 1 is household/operator-managed; actor scoping is enforced in core.

func (s *Store) ListSources(ctx context.Context) ([]*Source, error) {
	rows, err := s.db.QueryContext(ctx,
		`SELECT source_id, connector_id, verified_external_id, endpoint, display_name, status, status_detail, created_by, created, updated
		   FROM sources ORDER BY created DESC, source_id DESC`)
	if err != nil {
		return nil, fmt.Errorf("list sources: %w", err)
	}
	defer rows.Close()
	var out []*Source
	for rows.Next() {
		src := &Source{}
		if err := rows.Scan(&src.SourceID, &src.ConnectorID, &src.VerifiedExternalID, &src.Endpoint, &src.DisplayName, &src.Status, &src.StatusDetail, &src.CreatedBy, &src.Created, &src.Updated); err != nil {
			return nil, fmt.Errorf("list sources: %w", err)
		}
		out = append(out, src)
	}
	return out, rows.Err()
}

// UpdateSource applies allowed, already-verified changes to an existing source.
// Core must have re-verified and confirmed the verified identity is unchanged
// before calling this when the endpoint/connection changed (DEC-001 / proto).
// Identity fields (connector_id, verified_external_id) are immutable here.
// It returns ErrNotFound if the source does not exist.

func (s *Store) UpdateSource(ctx context.Context, sourceID, endpoint, displayName string, status int32, statusDetail string) (*Source, error) {
	now := time.Now().UTC()
	res, err := s.db.ExecContext(ctx,
		`UPDATE sources SET endpoint = ?, display_name = ?, status = ?, status_detail = ?, updated = ?
		  WHERE source_id = ?`,
		endpoint, displayName, status, statusDetail, now, sourceID,
	)
	if err != nil {
		return nil, fmt.Errorf("update source: %w", err)
	}
	n, err := res.RowsAffected()
	if err != nil {
		return nil, fmt.Errorf("update source: %w", err)
	}
	if n == 0 {
		return nil, ErrNotFound
	}
	return s.GetSource(ctx, sourceID)
}

