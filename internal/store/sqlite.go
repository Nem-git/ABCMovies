// Package store implements SQLite-backed persistence.
package store

import (
	"context"
	"crypto/rand"
	"database/sql"
	"encoding/hex"
	"errors"
	"fmt"
	"time"

	_ "modernc.org/sqlite"
)

// ErrNotFound is returned when a requested row does not exist.
var ErrNotFound = errors.New("not found")

// ErrAlreadyInitialized is returned when the instance already has an initial
// user and cannot be initialized again.
var ErrAlreadyInitialized = errors.New("already initialized")

// User represents a local ABCMovies user (e.g. the initial admin).
// user_id is the stable unique identifier; username is a login/display name.
type User struct {
	UserID   string
	Username string
	Hash     string
	Created  time.Time
}

// Session represents a logged-in session owned by a user.
type Session struct {
	ID      string
	UserID  string
	Created time.Time
	Expires time.Time
}

const schema = `
CREATE TABLE IF NOT EXISTS users (
    user_id   TEXT PRIMARY KEY,
    username  TEXT NOT NULL UNIQUE,
    hash      TEXT NOT NULL,
    created   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sessions (
    id        TEXT PRIMARY KEY,
    user_id   TEXT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    created   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires   TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expires ON sessions(expires);
`

// Store wraps the SQLite database.
type Store struct {
	db *sql.DB
}

// Open opens (and migrates) the store at path.
func Open(path string) (*Store, error) {
	db, err := sql.Open("sqlite", path)
	if err != nil {
		return nil, fmt.Errorf("open sqlite: %w", err)
	}
	// SQLite supports a single writer; serializing connections avoids SQLITE_BUSY
	// under concurrent access.
	db.SetMaxOpenConns(1)
	if _, err := db.ExecContext(context.Background(), schema); err != nil {
		db.Close()
		return nil, fmt.Errorf("migrate: %w", err)
	}
	s := &Store{db: db}
	// Best-effort cleanup of expired sessions on startup.
	_, _ = s.DeleteExpiredSessions(context.Background())
	return s, nil
}

// Close closes the database.
func (s *Store) Close() error { return s.db.Close() }

// HasUser reports whether any user exists (i.e. the instance is initialized).
func (s *Store) HasUser(ctx context.Context) (bool, error) {
	var exists bool
	if err := s.db.QueryRowContext(ctx, `SELECT EXISTS(SELECT 1 FROM users)`).Scan(&exists); err != nil {
		return false, fmt.Errorf("check initialized: %w", err)
	}
	return exists, nil
}

// CreateUser creates a user with the given username and password hash.
// It returns the new user; the user_id is generated by the store.
func (s *Store) CreateUser(ctx context.Context, username, hash string) (*User, error) {
	id := make([]byte, 16)
	if _, err := rand.Read(id); err != nil {
		return nil, fmt.Errorf("generate user id: %w", err)
	}
	u := &User{UserID: "usr_" + hex.EncodeToString(id), Username: username, Hash: hash}
	if _, err := s.db.ExecContext(ctx,
		`INSERT INTO users (user_id, username, hash) VALUES (?, ?, ?)`, u.UserID, u.Username, u.Hash); err != nil {
		return nil, fmt.Errorf("insert user: %w", err)
	}
	return u, nil
}

// CreateInitialUser atomically creates the initial user only if no users exist.
// It returns ErrAlreadyInitialized when the instance is already initialized.
func (s *Store) CreateInitialUser(ctx context.Context, username, hash string) (*User, error) {
	id := make([]byte, 16)
	if _, err := rand.Read(id); err != nil {
		return nil, fmt.Errorf("generate user id: %w", err)
	}
	u := &User{UserID: "usr_" + hex.EncodeToString(id), Username: username, Hash: hash}
	res, err := s.db.ExecContext(ctx,
		`INSERT INTO users (user_id, username, hash)
		SELECT ?, ?, ?
		WHERE NOT EXISTS (SELECT 1 FROM users)`,
		u.UserID, u.Username, u.Hash)
	if err != nil {
		return nil, fmt.Errorf("insert initial user: %w", err)
	}
	n, err := res.RowsAffected()
	if err != nil {
		return nil, fmt.Errorf("insert initial user: %w", err)
	}
	if n == 0 {
		return nil, ErrAlreadyInitialized
	}
	return u, nil
}

// GetUserByUsername returns the user with the given username, or ErrNotFound.
func (s *Store) GetUserByUsername(ctx context.Context, username string) (*User, error) {
	u := &User{}
	err := s.db.QueryRowContext(ctx,
		`SELECT user_id, username, hash, created FROM users WHERE username = ?`, username).Scan(&u.UserID, &u.Username, &u.Hash, &u.Created)
	if err == sql.ErrNoRows {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("get user by username: %w", err)
	}
	return u, nil
}

// GetUserByID returns the user with the given user_id, or ErrNotFound.
func (s *Store) GetUserByID(ctx context.Context, userID string) (*User, error) {
	u := &User{}
	err := s.db.QueryRowContext(ctx,
		`SELECT user_id, username, hash, created FROM users WHERE user_id = ?`, userID).Scan(&u.UserID, &u.Username, &u.Hash, &u.Created)
	if err == sql.ErrNoRows {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("get user by id: %w", err)
	}
	return u, nil
}

// CreateSession creates a session for userID with the given lifetime.
func (s *Store) CreateSession(ctx context.Context, userID string, ttl time.Duration) (*Session, error) {
	token := make([]byte, 32)
	if _, err := rand.Read(token); err != nil {
		return nil, fmt.Errorf("generate session id: %w", err)
	}
	now := time.Now().UTC()
	sess := &Session{
		ID:      hex.EncodeToString(token),
		UserID:  userID,
		Created: now,
		Expires: now.Add(ttl),
	}
	if _, err := s.db.ExecContext(ctx,
		`INSERT INTO sessions (id, user_id, created, expires) VALUES (?, ?, ?, ?)`,
		sess.ID, sess.UserID, sess.Created, sess.Expires); err != nil {
		return nil, fmt.Errorf("insert session: %w", err)
	}
	return sess, nil
}

// ValidateSession returns the session if it exists and has not expired, or ErrNotFound.
func (s *Store) ValidateSession(ctx context.Context, id string) (*Session, error) {
	sess := &Session{}
	err := s.db.QueryRowContext(ctx,
		`SELECT id, user_id, created, expires FROM sessions WHERE id = ? AND expires > ?`, id, time.Now().UTC()).Scan(&sess.ID, &sess.UserID, &sess.Created, &sess.Expires)
	if err == sql.ErrNoRows {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("validate session: %w", err)
	}
	return sess, nil
}

// DeleteSession removes the session with the given id, if any.
func (s *Store) DeleteSession(ctx context.Context, id string) error {
	if _, err := s.db.ExecContext(ctx, `DELETE FROM sessions WHERE id = ?`, id); err != nil {
		return fmt.Errorf("delete session: %w", err)
	}
	return nil
}

// GetAdminCredentials returns the user_id and username of the initial admin
// (the first user), or ErrNotFound when the instance is not initialized.
func (s *Store) GetAdminCredentials(ctx context.Context) (*User, error) {
	u := &User{}
	err := s.db.QueryRowContext(ctx,
		`SELECT user_id, username, hash, created FROM users ORDER BY created ASC, user_id ASC LIMIT 1`).Scan(&u.UserID, &u.Username, &u.Hash, &u.Created)
	if err == sql.ErrNoRows {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("get admin credentials: %w", err)
	}
	return u, nil
}

// SetPassword updates the given user's password hash and invalidates all of
// that user's sessions. It returns the number of sessions invalidated.
func (s *Store) SetPassword(ctx context.Context, userID, hash string) (int64, error) {
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return 0, fmt.Errorf("set password: begin: %w", err)
	}
	if _, err := tx.ExecContext(ctx, `UPDATE users SET hash = ? WHERE user_id = ?`, hash, userID); err != nil {
		_ = tx.Rollback()
		return 0, fmt.Errorf("set password: update hash: %w", err)
	}
	res, err := tx.ExecContext(ctx, `DELETE FROM sessions WHERE user_id = ?`, userID)
	if err != nil {
		_ = tx.Rollback()
		return 0, fmt.Errorf("set password: delete sessions: %w", err)
	}
	if err := tx.Commit(); err != nil {
		return 0, fmt.Errorf("set password: commit: %w", err)
	}
	return res.RowsAffected()
}

// DeleteExpiredSessions removes sessions whose expiry has passed. It is
// best-effort hygiene; validation already ignores expired sessions.
func (s *Store) DeleteExpiredSessions(ctx context.Context) (int64, error) {
	res, err := s.db.ExecContext(ctx, `DELETE FROM sessions WHERE expires <= ?`, time.Now().UTC())
	if err != nil {
		return 0, fmt.Errorf("delete expired sessions: %w", err)
	}
	return res.RowsAffected()
}
