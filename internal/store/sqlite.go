// CreateSession creates a session for userID with the given lifetime.
func (s *Store) CreateSession(ctx context.Context, userID string, ttl time.Duration) (*Session, error) {
	token := make([]byte, 32)
	if _, err := rand.Read(token); err != nil {
		return nil, fmt.Errorf("generate session id: %w", err)
	}
	now := time.Now().UTC()
	sess := &Session{
		ID:      hex.EncodeToString(token),
		UserID:  userID,
		Created: now,
		Expires: now.Add(ttl),
	}
	if _, err := s.db.ExecContext(ctx,
		`INSERT INTO sessions (id, user_id, created, expires) VALUES (?, ?, ?, ?)`,
		sess.ID, sess.UserID, sess.Created, sess.Expires); err != nil {
		return nil, fmt.Errorf("insert session: %w", err)
	}
	return sess, nil
}

// ValidateSession returns the session if it exists and has not expired, or ErrNotFound.
func (s *Store) ValidateSession(ctx context.Context, id string) (*Session, error) {
	sess := &Session{}
	err := s.db.QueryRowContext(ctx,
		`SELECT id, user_id, created, expires FROM sessions WHERE id = ? AND expires > ?`, id, time.Now().UTC()).Scan(&sess.ID, &sess.UserID, &sess.Created, &sess.Expires)
	if err == sql.ErrNoRows {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("validate session: %w", err)
	}
	return sess, nil
}

// DeleteSession removes the session with the given id, if any.
func (s *Store) DeleteSession(ctx context.Context, id string) error {
	if _, err := s.db.ExecContext(ctx, `DELETE FROM sessions WHERE id = ?`, id); err != nil {
		return fmt.Errorf("delete session: %w", err)
	}
	return nil
}

// GetAdminCredentials returns the user_id and username of the initial admin
// (the first user), or ErrNotFound when the instance is not initialized.
func (s *Store) GetAdminCredentials(ctx context.Context) (*User, error) {
	u := &User{}
	err := s.db.QueryRowContext(ctx,
		`SELECT user_id, username, hash, created FROM users ORDER BY created ASC, user_id ASC LIMIT 1`).Scan(&u.UserID, &u.Username, &u.Hash, &u.Created)
	if err == sql.ErrNoRows {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("get admin credentials: %w", err)
	}
	return u, nil
}

// SetPassword updates the given user's password hash and invalidates all of
// that user's sessions. It returns the number of sessions invalidated.
func (s *Store) SetPassword(ctx context.Context, userID, hash string) (int64, error) {
	tx, err := s.db.BeginTx(ctx, nil)
	if err != nil {
		return 0, fmt.Errorf("set password: begin: %w", err)
	}
	if _, err := tx.ExecContext(ctx, `UPDATE users SET hash = ? WHERE user_id = ?`, hash, userID); err != nil {
		_ = tx.Rollback()
		return 0, fmt.Errorf("set password: update hash: %w", err)
	}
	res, err := tx.ExecContext(ctx, `DELETE FROM sessions WHERE user_id = ?`, userID)
	if err != nil {
		_ = tx.Rollback()
		return 0, fmt.Errorf("set password: delete sessions: %w", err)
	}
	if err := tx.Commit(); err != nil {
		return 0, fmt.Errorf("set password: commit: %w", err)
	}
	return res.RowsAffected()
}

// DeleteExpiredSessions removes sessions whose expiry has passed. It is
// best-effort hygiene; validation already ignores expired sessions.
func (s *Store) DeleteExpiredSessions(ctx context.Context) (int64, error) {
	res, err := s.db.ExecContext(ctx, `DELETE FROM sessions WHERE expires <= ?`, time.Now().UTC())
	if err != nil {
		return 0, fmt.Errorf("delete expired sessions: %w", err)
	}
	return res.RowsAffected()
}

// GetSourceByVerifiedIdentity returns the source for (connector_id,
// verified_external_id), or ErrNotFound. Used for duplicate detection (DEC-001).
// Build 1 scope is instance-level (household/operator); future public/multi-user
// dedup visibility must be scoped by a follow-up decision.
func (s *Store) GetSourceByVerifiedIdentity(ctx context.Context, connectorID, verifiedExternalID string) (*Source, error) {
	src := &Source{}
	err := s.db.QueryRowContext(ctx,
		`SELECT source_id, connector_id, verified_external_id, endpoint, display_name, status, status_detail, created_by, created, updated
		   FROM sources WHERE connector_id = ? AND verified_external_id = ?`,
		connectorID, verifiedExternalID,
	).Scan(&src.SourceID, &src.ConnectorID, &src.VerifiedExternalID, &src.Endpoint, &src.DisplayName, &src.Status, &src.StatusDetail, &src.CreatedBy, &src.Created, &src.Updated)
	if err == sql.ErrNoRows {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("get source by verified identity: %w", err)
	}
	return src, nil
}

// CreateSource inserts a verified, connected source and returns it.
// The source_id is generated by the store. A uniqueness violation on
// (connector_id, verified_external_id) is returned as an error (core should
// dedup first via GetSourceByVerifiedIdentity; the UNIQUE constraint is the
// final guard).
func (s *Store) CreateSource(ctx context.Context, in Source) (*Source, error) {
	id := make([]byte, 16)
	if _, err := rand.Read(id); err != nil {
		return nil, fmt.Errorf("generate source id: %w", err)
	}
	now := time.Now().UTC()
	src := in
	src.SourceID = "src_" + hex.EncodeToString(id)
	src.Created = now
	src.Updated = now
	if _, err := s.db.ExecContext(ctx,
		`INSERT INTO sources (source_id, connector_id, verified_external_id, endpoint, display_name, status, status_detail, created_by, created, updated)
		 VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		src.SourceID, src.ConnectorID, src.VerifiedExternalID, src.Endpoint, src.DisplayName, src.Status, src.StatusDetail, src.CreatedBy, src.Created, src.Updated,
	); err != nil {
		if isUniqueConstraint(err) {
			return nil, ErrDuplicateVerifiedIdentity
		}
		return nil, fmt.Errorf("insert source: %w", err)
	}
	return &src, nil
}

// GetSource returns the source with the given source_id, or ErrNotFound.
func (s *Store) GetSource(ctx context.Context, sourceID string) (*Source, error) {
	src := &Source{}
	err := s.db.QueryRowContext(ctx,
		`SELECT source_id, connector_id, verified_external_id, endpoint, display_name, status, status_detail, created_by, created, updated
		   FROM sources WHERE source_id = ?`, sourceID,
	).Scan(&src.SourceID, &src.ConnectorID, &src.VerifiedExternalID, &src.Endpoint, &src.DisplayName, &src.Status, &src.StatusDetail, &src.CreatedBy, &src.Created, &src.Updated)
	if err == sql.ErrNoRows {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("get source: %w", err)
	}
	return src, nil
}

// ListSources returns all connected sources (non-sensitive summaries), newest first.
// Build 1 is household/operator-managed; actor scoping is enforced in core.
func (s *Store) ListSources(ctx context.Context) ([]*Source, error) {
	rows, err := s.db.QueryContext(ctx,
		`SELECT source_id, connector_id, verified_external_id, endpoint, display_name, status, status_detail, created_by, created, updated
		   FROM sources ORDER BY created DESC, source_id DESC`)
	if err != nil {
		return nil, fmt.Errorf("list sources: %w", err)
	}
	defer rows.Close()
	var out []*Source
	for rows.Next() {
		src := &Source{}
		if err := rows.Scan(&src.SourceID, &src.ConnectorID, &src.VerifiedExternalID, &src.Endpoint, &src.DisplayName, &src.Status, &src.StatusDetail, &src.CreatedBy, &src.Created, &src.Updated); err != nil {
			return nil, fmt.Errorf("list sources: %w", err)
		}
		out = append(out, src)
	}
	return out, rows.Err()
}

// UpdateSource applies allowed, already-verified changes to an existing source.
// Core must have re-verified and confirmed the verified identity is unchanged
// before calling this when the endpoint/connection changed (DEC-001 / proto).
// Identity fields (connector_id, verified_external_id) are immutable here.
// It returns ErrNotFound if the source does not exist.
func (s *Store) UpdateSource(ctx context.Context, sourceID, endpoint, displayName string, status int32, statusDetail string) (*Source, error) {
	now := time.Now().UTC()
	res, err := s.db.ExecContext(ctx,
		`UPDATE sources SET endpoint = ?, display_name = ?, status = ?, status_detail = ?, updated = ?
		  WHERE source_id = ?`,
		endpoint, displayName, status, statusDetail, now, sourceID,
	)
	if err != nil {
		return nil, fmt.Errorf("update source: %w", err)
	}
	n, err := res.RowsAffected()
	if err != nil {
		return nil, fmt.Errorf("update source: %w", err)
	}
	if n == 0 {
		return nil, ErrNotFound
	}
	return s.GetSource(ctx, sourceID)
}

// isUniqueConstraint reports whether err is an SQLite UNIQUE/PRIMARY KEY
// constraint violation. modernc sqlite reports extended code 2067
// (SQLITE_CONSTRAINT_UNIQUE) / 1555; match the message text as well so the
// checks stay robust across driver versions.
func isUniqueConstraint(err error) bool {
	var serr *sqlite.Error
	if errors.As(err, &serr) {
		return serr.Code() == 2067 || serr.Code() == 1555 || serr.Code()&0xff == 19
	}
	msg := err.Error()
	return strings.Contains(msg, "UNIQUE constraint failed") || strings.Contains(msg, "2067") || strings.Contains(msg, "1555")
}
